_KIND_FMT = {"u16": "H", "i16": "h", "u32": "I", "i32": "i", "u64": "Q", "i64": "q"}
_KIND_SIZE = {"u16": 2, "i16": 2, "u32": 4, "i32": 4, "u64": 8, "i64": 8}


class Reader:
    """Bounds-checked struct reader over an immutable bytes buffer."""

    def __init__(self, data: bytes, endian: str = "<"):
        self.data = data
        self.endian = endian

    def __len__(self):
        return len(self.data)

    def check(self, offset: int, size: int, what: str):
        if offset < 0 or size < 0 or offset + size > len(self.data):
            raise MapFormatError(
                "%s: wants bytes [0x%X, 0x%X) but the file is 0x%X bytes long"
                % (what, offset, offset + size, len(self.data)))

    def scalar(self, kind: str, offset: int, what: str = "scalar"):
        size = _KIND_SIZE[kind]
        self.check(offset, size, "%s (%s @ 0x%X)" % (what, kind, offset))
        return struct.unpack_from(self.endian + _KIND_FMT[kind], self.data, offset)[0]

    def raw(self, offset: int, size: int, what: str = "block") -> bytes:
        self.check(offset, size, what)
        return self.data[offset:offset + size]

    def asciiz(self, offset: int, window: int = 0x20, what: str = "string") -> str:
        self.check(offset, window, what)
        blob = self.data[offset:offset + window]
        blob = blob.split(b"\x00", 1)[0]
        return blob.decode("latin-1")

    def asciiz_unbounded(self, offset: int, limit: int = 0x400, what: str = "string") -> str:
        self.check(offset, 1, what)
        end = self.data.find(b"\x00", offset, min(len(self.data), offset + limit))
        if end < 0:
            raise MapFormatError("%s at 0x%X is not NUL-terminated within 0x%X bytes"
                                 % (what, offset, limit))
        return self.data[offset:end].decode("latin-1")


def fourcc(value: int) -> str:
    """Group magic int -> four-character code.

    Assembly stores group magics as ``CharConstant.FromString("scnr")`` i.e.
    ('s'<<24)|('c'<<16)|('n'<<8)|'r', independent of file endianness, so the
    integer always renders big-endian.  SYNTHETIC-PROVEN.
    """
    v = value & 0xFFFFFFFF
    return struct.pack(">I", v).decode("latin-1")


def fourcc_to_int(code: str) -> int:
    code = code.encode("latin-1")
    if len(code) != 4:
        raise ValueError("group codes are 4 characters: %r" % code)
    return struct.unpack(">I", code)[0]


def printable_ratio(s: str) -> float:
    if not s:
        return 0.0
    ok = sum(1 for c in s if 0x20 <= ord(c) < 0x7F)
    return ok / len(s)


