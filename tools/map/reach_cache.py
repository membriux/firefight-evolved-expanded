@dataclass(frozen=True)
class HeaderVariant:
    name: str
    engine_version: int
    endian: str                   # struct prefix: "<" little, ">" big
    header_size: int
    expand_magic: int             # 0 = pointers are not contracted
    fields: dict                  # logical name -> (kind, offset)
    partitions: tuple             # (offset, count, entry_size, addr_kind)
    offset_masks: int             # offset of 4 x uint32
    sections: int                 # offset of 4 x (uint32 vaddr, uint32 size)
    index_header: IndexHeaderSpec
    encrypted_names: bool = False
    notes: str = ""

    def field(self, name):
        return self.fields.get(name)

    def str_window(self, name: str) -> int:
        """How many bytes an ``asciiz`` field may span.

        Assembly's layouts give ``asciiz`` fields no size, so a string runs to
        its NUL. Here the window is the distance to the next header field
        (clamped to 0x100) so a missing NUL cannot run away across the header.
        Scenario paths are longer than 0x20 bytes, so a fixed 0x20 window would
        silently truncate them.
        """
        kind, off = self.fields[name]
        later = [o for (_k, o) in self.fields.values() if o > off]
        gap = (min(later) - off) if later else 0x100
        return max(0x20, min(gap, 0x100))


