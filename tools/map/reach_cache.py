class ReachCacheFile:
    """A parsed Halo: Reach cache file.

    Usage::

        cache = ReachCacheFile.from_path("cex_ff_halo.map")
        print(cache.header["scenario_name"], len(cache.tags))
        for tag in cache.tags_of_group("scnr"):
            blob = cache.tag_bytes(tag)
    """

    # -- construction -------------------------------------------------------

    def __init__(self, data: bytes, path: str | None = None, force_variant: str | None = None):
        self.path = path
        self.data = data
        self.diag = Diagnostics()
        self.variant = None
        self.engine_name = None
        self.build_string = None
        self.header = {}
        self.sections = []
        self.offset_masks = []
        self.partitions = []
        self.meta_offset = 0
        self.meta_size = 0
        self.virtual_base = 0
        self.index_header = {}
        self.groups = []
        self.tags = []
        self.global_tags = {}
        self.interops = []
        self.tag_names = []
        self.stringids = []
        self._sid_namespaces = []     # (ns_id, min_index, global_index)
        self._group_by_code = {}

        self._detect(force_variant)
        self._read_header()
        self._read_tables()
        self._read_index()
        self._resolve_names()
        self.estimate_sizes()

    @classmethod
    def from_path(cls, path, force_variant: str | None = None) -> "ReachCacheFile":
        p = Path(path)
        if not p.is_file():
            raise MapFormatError("not a file: %s" % p)
        data = p.read_bytes()
        if len(data) < 0x1000:
            raise MapFormatError("%s is only %d bytes; a Reach cache header alone is 0x%X bytes"
                                 % (p, len(data), 0xA000))
        return cls(data, path=str(p), force_variant=force_variant)

    # -- step 1: magic, endianness, version, layout variant -----------------

    def _detect(self, force_variant):
        data = self.data
        head = data[:4]
        if head == HEADER_MAGIC_LE:
            endian = "<"
        elif head == HEADER_MAGIC_BE:
            endian = ">"
        else:
            findings = probe_compression(data)
            raise CompressedCacheError(
                "no cache header magic at offset 0 (found %r, expected %r little-endian or %r big-endian).\n"
                "Triage:\n  - %s\n"
                "If this file is compressed, decompress it first (Assembly: Tools > Map Compressor), "
                "or use reach_cache.decompress_saber_gen1/gen2 if the triage above names one of those schemes."
                % (head, HEADER_MAGIC_LE, HEADER_MAGIC_BE, "\n  - ".join(findings)))

        self.endian = endian
        self.reader = Reader(data, endian)
        self.engine_version = self.reader.scalar("i32", 0x4, "engine version")

        # footer magic: Assembly looks at engine.HeaderSize - 4 (0xA000 - 4 for Reach)
        self.footer_ok = False
        self.header_size_guess = 0xA000
        for hsize in (0xA000, 0x3000, 0x1000, 0x800):
            if hsize <= len(data):
                if data[hsize - 4:hsize] in FOOTER_MAGICS:
                    self.footer_ok = True
                    self.header_size_guess = hsize
                    break
        if not self.footer_ok:
            self.diag.warn("no 'foot'/'toof' footer magic at 0xA000-4 (or 0x3000/0x1000/0x800-4). "
                           "Header may be truncated or this is not a Reach-era cache.")
        elif self.header_size_guess != 0xA000:
            self.diag.warn("footer magic found at 0x%X-4, not at 0xA000-4: this does not look like a "
                           "Reach cache (Reach's header is 0xA000 bytes)" % self.header_size_guess)

        # Preferred path (Assembly's own): match the build string.
        candidates = [v for v in VARIANTS if v.endian == endian]
        if force_variant:
            chosen = next((v for v in VARIANTS if v.name == force_variant), None)
            if chosen is None:
                raise MapFormatError("unknown --variant %r; known: %s"
                                     % (force_variant, ", ".join(v.name for v in VARIANTS)))
            self.variant = chosen
            self.build_string = self._read_build_string(chosen)
            self.engine_name = BUILD_TABLE.get(self.build_string, (None, "forced, build string unknown"))[1]
            self.detection = "forced by caller"
            self.diag.warn("header layout forced to %r; no validation of that choice was done" % force_variant)
            return

        by_build = {}
        for v in candidates:
            s = self._read_build_string(v)
            if s in BUILD_TABLE and BUILD_TABLE[s][0] == v.name:
                by_build[v.name] = (v, s)
        if len(by_build) == 1:
            v, s = next(iter(by_build.values()))
            self.variant, self.build_string = v, s
            self.engine_name = BUILD_TABLE[s][1]
            self.detection = "build string %r matched Engines.xml -> layout %s" % (s, v.name)
            return
        if len(by_build) > 1:
            # Two layouts agreeing on a build string would be an Engines.xml bug;
            # pick the newest layout and say so.
            v, s = by_build[sorted(by_build)[-1]]
            self.variant, self.build_string = v, s
            self.engine_name = BUILD_TABLE[s][1]
            self.detection = "build string %r matched several layouts (%s); chose %s" % (
                s, ", ".join(sorted(by_build)), v.name)
            self.diag.warn(self.detection)
            return

        # Fallback: structural scoring. Loudly flagged - MCC keeps shipping
        # updates, so an unknown build string is expected eventually. A layout
        # is only accepted if its index-header address resolves to a structure
        # whose magic really is 'tags'; nothing weaker is good enough.
        scored = sorted(((self._score_variant(v), v) for v in candidates),
                        key=lambda t: (-int(t[0][2]), -t[0][0]))
        (best_score, best_detail, best_index_ok), best = scored[0]
        table = "; ".join("%s=%d%s" % (v.name, sc[0], "" if sc[2] else " (index header invalid)")
                          for sc, v in scored)
        if not best_index_ok:
            raise UnknownBuildError(
                "cache header found (version %d, %s-endian) but no layout fits it.\n"
                "Scores: %s\nBest candidate %s failed: %s\n"
                "Either this is not Halo: Reach, or it is a newer MCC build whose header moved again. "
                "Dump 0x0..0x400 and compare against research/07-map-container-format.md, "
                "or pass --variant to force a layout."
                % (self.engine_version, "little" if endian == "<" else "big",
                   table, best.name, "; ".join(best_detail)))
        self.variant = best
        self.build_string = self._read_build_string(best)
        self.engine_name = BUILD_TABLE.get(self.build_string, (None, None))[1]
        self.detection = "build string %r is NOT in the known table; layout inferred by structural scoring (%s)" % (
            self.build_string, table)
        self.diag.warn("UNKNOWN BUILD: " + self.detection)
        self.diag.warn("Treat every header field below as unverified until the layout is confirmed.")

    def _read_build_string(self, variant: HeaderVariant) -> str:
        kind, off = variant.fields["build_string"]
        try:
            return Reader(self.data, variant.endian).asciiz(off, 0x20, "build string")
        except MapFormatError:
            return ""

    def _score_variant(self, variant: HeaderVariant):
        """Cheap structural validation; returns (score, failures, index_header_ok)."""
        r = Reader(self.data, variant.endian)
        score, fails, index_ok = 0, [], False

        def get(name):
            spec = variant.fields.get(name)
            if spec is None:
                return None
            kind, off = spec
            if kind == "str":
                return r.asciiz(off, variant.str_window(name), name)
            return r.scalar(kind, off, name)

        try:
            if variant.engine_version == self.engine_version:
                score += 1
            else:
                fails.append("engine version %d != layout's %d" % (self.engine_version, variant.engine_version))

            fs = get("file_size")
            if fs == len(self.data):
                score += 2
            else:
                fails.append("file size field 0x%X != actual 0x%X" % (fs or 0, len(self.data)))

            t = get("type")
            if t in CACHE_FILE_TYPES:
                score += 1
            else:
                fails.append("cache type %r not in 0..4" % t)

            scen = get("scenario_name") or ""
            if scen and printable_ratio(scen) > 0.95 and ("\\" in scen or "/" in scen):
                score += 2
            else:
                fails.append("scenario name %r is not a printable path" % scen[:48])

            name = get("internal_name") or ""
            if name and printable_ratio(name) > 0.95:
                score += 1
            else:
                fails.append("internal name %r not printable" % name[:32])

            bstr = get("build_string") or ""
            if bstr and printable_ratio(bstr) > 0.95:
                score += 1
            else:
                fails.append("build string %r not printable" % bstr[:32])

            sections = self._read_sections(r, variant)
            masks = self._read_masks(r, variant)
            tag_off = (sections[SECTION_TAG][0] + masks[SECTION_TAG]) & 0xFFFFFFFF
            vsize = get("virtual_size") or 0
            if 0 < tag_off < len(self.data) and 0 < vsize and tag_off + vsize <= len(self.data) + 0x10000:
                score += 1
            else:
                fails.append("tag section (vaddr 0x%X + mask 0x%X, virtual size 0x%X) is outside the file"
                             % (sections[SECTION_TAG][0], masks[SECTION_TAG], vsize))

            # The decisive discriminator between two layouts that differ only in
            # where the interop arrays live (mcc-u8 at 0x4AC/0x4BC versus
            # mcc-u8+ at 0x4CC/0x4DC): with the right offsets the four sections
            # tile the file from the end of the header to EOF with no gap and no
            # overlap. With the wrong ones they land past 0x1_00000000 and do
            # not tile. See research/19-holdout-retarget.md §1.
            spans = sorted(((s[0] + m) & 0xFFFFFFFF, s[1])
                           for s, m in zip(sections, masks) if s[1])
            cursor = variant.header_size
            tiles = bool(spans)
            for off, size in spans:
                if off != cursor:
                    tiles = False
                    break
                cursor += size
            if tiles and cursor == len(self.data):
                score += 3
            else:
                fails.append("the four interop sections do not tile the file from 0x%X to 0x%X "
                             "with these array offsets (0x%X/0x%X)"
                             % (variant.header_size, len(self.data),
                                variant.offset_masks, variant.sections))

            vbase = get("virtual_base_address") or 0
            idx = get("index_header_address") or 0
            ioff = idx - vbase + tag_off
            if 0 <= ioff <= len(self.data) - variant.index_header.size:
                magic = r.raw(ioff + variant.index_header.magic, 4, "index magic")
                want = b"sgat" if variant.endian == "<" else b"tags"
                if magic == want:
                    score += 4
                    index_ok = True
                else:
                    fails.append("index header at 0x%X has magic %r, expected %r" % (ioff, magic, want))
            else:
                fails.append("index header address 0x%X maps outside the file (offset 0x%X)" % (idx, ioff))
        except MapFormatError as exc:
            fails.append(str(exc))
        return (score, fails, index_ok)

    # -- step 2: header -----------------------------------------------------

    @staticmethod
    def _read_sections(r: Reader, variant: HeaderVariant):
        out = []
        for i in range(4):
            base = variant.sections + i * 8
            out.append((r.scalar("u32", base, "section %d vaddr" % i),
                        r.scalar("u32", base + 4, "section %d size" % i)))
        return out

    @staticmethod
    def _read_masks(r: Reader, variant: HeaderVariant):
        return [r.scalar("u32", variant.offset_masks + i * 4, "offset mask %d" % i) for i in range(4)]

    def _read_header(self):
        v = self.variant
        r = Reader(self.data, v.endian)
        self.reader = r
        hdr = {}
        for name, (kind, off) in v.fields.items():
            if kind == "str":
                hdr[name] = r.asciiz(off, v.str_window(name), name)
            else:
                hdr[name] = r.scalar(kind, off, name)
        self.header = hdr

        self.sections = self._read_sections(r, v)
        self.offset_masks = self._read_masks(r, v)

        poff, pcount, psize, pkind = v.partitions
        self.partitions = []
        for i in range(pcount):
            base = poff + i * psize
            self.partitions.append({
                "load_address": r.scalar(pkind, base, "partition %d load address" % i),
                "size": r.scalar(pkind, base + _KIND_SIZE[pkind], "partition %d size" % i),
            })

        if hdr.get("file_size") != len(self.data):
            self.diag.warn("header file size 0x%X != actual file size 0x%X (mod tools often leave this stale)"
                           % (hdr.get("file_size", 0), len(self.data)))

        self.virtual_base = hdr["virtual_base_address"]
        self.meta_size = hdr["virtual_size"]

        # Tag-data ("meta") area, per ThirdGenHeader.CalculateTagDataSegment:
        #   file offset of the tag section = section.virtual_address + offset_mask
        if any(s[0] or s[1] for s in self.sections):
            # Real MCC caches store the mask as a 32-bit wrapping delta: the tag
            # section's mask is usually negative (e.g. vaddr 0x4D8E000 +
            # mask 0xFE4BB000 = 0x1_03249000 -> 0x3249000). Without the 32-bit
            # truncation every real map reports a tag-data offset past EOF.
            self.meta_offset = (self.sections[SECTION_TAG][0]
                                + self.offset_masks[SECTION_TAG]) & 0xFFFFFFFF
            self.debug_mask = self.offset_masks[SECTION_DEBUG]
            self.section_source = "interop sections"
            if self.meta_offset != hdr.get("tag_buffer_offset"):
                self.diag.note("tag section offset 0x%X differs from the header's tag buffer offset 0x%X "
                               "(expected when offset masks are non-zero)"
                               % (self.meta_offset, hdr.get("tag_buffer_offset", 0)))
        else:
            # Assembly's fallback when a build has no interop section table.
            self.meta_offset = hdr.get("tag_buffer_offset", 0)
            self.debug_mask = 0
            self.section_source = "fallback: header tag buffer offset (section table was all zeroes)"
            self.diag.warn("interop section table is all zeroes; falling back to the tag buffer offset. "
                           "String/file table offsets are being treated as raw file offsets.")

        if not (0 < self.meta_offset < len(self.data)):
            raise MapFormatError("tag data area offset 0x%X is outside the file (0x%X bytes)"
                                 % (self.meta_offset, len(self.data)))
        if self.meta_offset + self.meta_size > len(self.data):
            self.diag.warn("tag data area 0x%X + virtual size 0x%X runs past EOF 0x%X; clamping"
                           % (self.meta_offset, self.meta_size, len(self.data)))
            self.meta_size = len(self.data) - self.meta_offset

    # -- pointer conversion -------------------------------------------------

    def expand(self, pointer: int) -> int:
        """Contracted 32-bit pointer -> virtual address.

        MCC stores tag/tag-block pointers as ``address = (virtual >> 2) - magic``;
        Assembly's ThirdGenPointerExpander reverses it as ``(p << 2) + magic``.
        Xbox 360 maps are not contracted (expand_magic == 0).
        """
        if not pointer:
            return 0
        if self.variant.expand_magic:
            return (pointer << 2) + self.variant.expand_magic
        return pointer

    def meta_to_offset(self, address: int, what: str = "meta pointer") -> int:
        """Virtual address inside the tag area -> file offset. MetaAddressConverter."""
        off = address - self.virtual_base + self.meta_offset
        if not (0 <= off < len(self.data)):
            raise MapFormatError("%s: address 0x%X maps to offset 0x%X, outside the file (0x%X)"
                                 % (what, address, off, len(self.data)))
        return off

    def offset_to_meta(self, offset: int) -> int:
        return offset - self.meta_offset + self.virtual_base

    def debug_to_offset(self, pointer: int, what: str = "debug pointer") -> int:
        """Pointer in the debug section (string/file tables) -> file offset.

        BasedPointerConverter(base=section.vaddr, start=section.vaddr+mask)
        reduces to ``offset = pointer + mask``.
        """
        off = (pointer + self.debug_mask) & 0xFFFFFFFF
        if not (0 <= off < len(self.data)):
            raise MapFormatError("%s: 0x%X + mask 0x%X = 0x%X, outside the file (0x%X)"
                                 % (what, pointer, self.debug_mask, off, len(self.data)))
        return off

    def meta_contains(self, address: int) -> bool:
        off = address - self.virtual_base + self.meta_offset
        return self.meta_offset <= off < self.meta_offset + self.meta_size

    # -- step 3: string / file name tables ----------------------------------

    def _read_indexed_strings(self, count: int, index_table_ptr: int, data_ptr: int,
                              data_size: int, what: str, encrypted: bool):
        if count <= 0:
            return []
        if count > 1_000_000:
            raise MapFormatError("%s: implausible count %d" % (what, count))
        idx_off = self.debug_to_offset(index_table_ptr, "%s index table" % what)
        dat_off = self.debug_to_offset(data_ptr, "%s data" % what)
        self.reader.check(idx_off, count * 4, "%s index table" % what)
        self.reader.check(dat_off, max(data_size, 1), "%s data" % what)
        if encrypted:
            self.diag.warn("%s is AES-encrypted on this engine (Xbox 360); returning placeholders" % what)
            return ["<encrypted>"] * count
        offsets = struct.unpack_from(self.endian + "%di" % count, self.data, idx_off)
        blob = self.data[dat_off:dat_off + data_size]
        out = []
        bad = 0
        for i, off in enumerate(offsets):
            if off < 0 or off >= len(blob):
                out.append(None)
                if off != -1:
                    bad += 1
                continue
            end = blob.find(b"\x00", off)
            out.append(blob[off:end if end >= 0 else len(blob)].decode("latin-1"))
        if bad:
            self.diag.warn("%s: %d of %d entries had offsets outside the %d-byte data blob"
                           % (what, bad, count, len(blob)))
        return out

    def _read_tables(self):
        hdr = self.header
        self.tag_names = self._read_indexed_strings(
            hdr.get("file_table_count", 0), hdr.get("file_index_table_offset", 0),
            hdr.get("file_table_offset", 0), hdr.get("file_table_size", 0),
            "tag name table", self.variant.encrypted_names)

        self.stringids = self._read_indexed_strings(
            hdr.get("string_table_count", 0), hdr.get("string_index_table_offset", 0),
            hdr.get("string_table_offset", 0), hdr.get("string_table_size", 0),
            "string id table", self.variant.encrypted_names)

        # string-id namespaces (MCC U3+ only); see ThirdGenCacheFile.LoadStringIDNamespaces
        ns_count = hdr.get("string_namespace_table_count", 0) or 0
        if ns_count > 1:
            ns_off = self.debug_to_offset(hdr["string_namespace_table_offset"], "string namespace table")
            self.reader.check(ns_off, ns_count * 4, "string namespace table")
            counts = struct.unpack_from(self.endian + "%di" % ns_count, self.data, ns_off)
            index_mask = (1 << SID_INDEX_BITS) - 1
            ns = []
            counter = counts[0] & index_mask
            for i in range(1, ns_count):
                ns.append((i, 0, counter))
                counter += counts[i] & index_mask
            ns.append((0, counts[0] & index_mask, counter))
            self._sid_namespaces = sorted(ns)
            self.diag.note("resolved %d string-id namespaces from the cache's own namespace table" % ns_count)
        elif self.stringids:
            self.diag.warn("this build has no in-cache string-id namespace table; string-id values are being "
                           "resolved as plain indices, which is wrong for namespaced ids "
                           "(Assembly uses Formats/Reach*/..._StringIDs.xml for these builds)")

    def resolve_sid(self, value: int) -> str:
        """String-id value -> string.

        Reach layout (Reach_StringIDs.xml): index = bits 0..16, namespace =
        bits 17..24, length = bits 25..31.  Namespace -> global index per
        Assembly's StringIDNamespaceResolver, but computed on the index field
        only (Assembly subtracts whole values, which assumes length == 0).
        """
        if value in (0, 0xFFFFFFFF):
            return ""
        index = value & ((1 << SID_INDEX_BITS) - 1)
        namespace = (value >> SID_INDEX_BITS) & ((1 << SID_NAMESPACE_BITS) - 1)
        resolved = index
        if self._sid_namespaces:
            chosen = None
            for ns in self._sid_namespaces:
                if ns[0] <= namespace:
                    chosen = ns
                else:
                    break
            if chosen is not None and index < chosen[1]:
                # index falls below this namespace's first index: it belongs to
                # the previous namespace. With no previous namespace Assembly
                # gives up and uses the raw value, so use the raw index here.
                prev = [n for n in self._sid_namespaces if n[0] < chosen[0]]
                chosen = prev[-1] if prev else None
            if chosen is not None:
                resolved = index - chosen[1] + chosen[2]
        if 0 <= resolved < len(self.stringids) and self.stringids[resolved]:
            return self.stringids[resolved]
        return "<sid 0x%08X>" % value

    # -- step 4: tag index --------------------------------------------------

    def _read_index(self):
        v = self.variant
        spec = v.index_header
        addr = self.header["index_header_address"]
        ioff = self.meta_to_offset(addr, "index header address")
        magic = self.reader.raw(ioff + spec.magic, 4, "index header magic")
        want = b"sgat" if self.endian == "<" else b"tags"
        if magic != want:
            raise MapFormatError(
                "index header at 0x%X (address 0x%X) has magic %r, expected %r ('tags'). "
                "Either the header layout is wrong or the tag area offset is wrong "
                "(tag section 0x%X + mask 0x%X, virtual base 0x%X)."
                % (ioff, addr, magic, want, self.sections[SECTION_TAG][0],
                   self.offset_masks[SECTION_TAG], self.virtual_base))

        rd = self.reader
        ih = {
            "offset": ioff,
            "group_count": rd.scalar("i32", ioff + spec.group_count, "tag group count"),
            "group_table_address": rd.scalar(spec.ptr_kind, ioff + spec.group_table, "tag group table address"),
            "tag_count": rd.scalar("i32", ioff + spec.tag_count, "tag count"),
            "tag_table_address": rd.scalar(spec.ptr_kind, ioff + spec.tag_table, "tag table address"),
            "global_count": rd.scalar("i32", ioff + spec.global_count, "global tag count"),
            "global_table_address": rd.scalar(spec.ptr_kind, ioff + spec.global_table, "global tag table address"),
            "interop_count": rd.scalar("i32", ioff + spec.interop_count, "tag interop count"),
            "interop_table_address": rd.scalar(spec.ptr_kind, ioff + spec.interop_table, "tag interop table address"),
        }
        self.index_header = ih

        for key in ("group_count", "tag_count", "global_count", "interop_count"):
            n = ih[key]
            if not (0 <= n <= 0x10000):
                raise MapFormatError("index header %s is %d, which is not plausible (0..65536)" % (key, n))

        # tag groups: 0x10 bytes each
        self.groups = []
        goff = self.meta_to_offset(ih["group_table_address"], "tag group table")
        rd.check(goff, ih["group_count"] * 0x10, "tag group table")
        for i in range(ih["group_count"]):
            b = goff + i * 0x10
            g = TagGroup(
                index=i,
                magic=rd.scalar("u32", b + 0x0, "group %d magic" % i),
                parent_magic=rd.scalar("u32", b + 0x4, "group %d parent" % i),
                grandparent_magic=rd.scalar("u32", b + 0x8, "group %d grandparent" % i),
                name_sid=rd.scalar("u32", b + 0xC, "group %d name sid" % i),
            )
            g.code = fourcc(g.magic)
            g.parent_code = fourcc(g.parent_magic) if g.parent_magic != 0xFFFFFFFF else ""
            self.groups.append(g)
            self._group_by_code.setdefault(g.code, g)

        # tags: 0x8 bytes each
        self.tags = []
        toff = self.meta_to_offset(ih["tag_table_address"], "tag table")
        rd.check(toff, ih["tag_count"] * 0x8, "tag table")
        for i in range(ih["tag_count"]):
            b = toff + i * 8
            gi = rd.scalar("i16", b + 0x0, "tag %d group index" % i)
            salt = rd.scalar("u16", b + 0x2, "tag %d salt" % i)
            raw = rd.scalar("u32", b + 0x4, "tag %d address" % i)
            entry = TagEntry(index=i, salt=salt, group_index=gi, raw_address=raw, address=0)
            if raw not in (0, 0xFFFFFFFF):
                entry.address = self.expand(raw)
                try:
                    entry.offset = self.meta_to_offset(entry.address, "tag %d data" % i)
                except MapFormatError as exc:
                    self.diag.warn("tag %d: %s" % (i, exc))
                    entry.offset = None
            if 0 <= gi < len(self.groups):
                entry.group_code = self.groups[gi].code
            elif gi != -1:
                self.diag.warn("tag %d has group index %d, outside the %d-entry group table"
                               % (i, gi, len(self.groups)))
            self.tags.append(entry)

        # global tags: group magic -> datum index
        self.global_tags = {}
        if ih["global_count"]:
            off = self.meta_to_offset(ih["global_table_address"], "global tag table")
            rd.check(off, ih["global_count"] * 8, "global tag table")
            for i in range(ih["global_count"]):
                b = off + i * 8
                magic = rd.scalar("u32", b, "global %d magic" % i)
                datum = rd.scalar("u32", b + 4, "global %d datum" % i)
                self.global_tags[fourcc(magic)] = datum & 0xFFFF

        # tag interops (pointer, type)
        self.interops = []
        if ih["interop_count"]:
            off = self.meta_to_offset(ih["interop_table_address"], "tag interop table")
            rd.check(off, ih["interop_count"] * 8, "tag interop table")
            for i in range(ih["interop_count"]):
                b = off + i * 8
                self.interops.append({
                    "pointer": rd.scalar("u32", b, "interop %d pointer" % i),
                    "type": rd.scalar("i32", b + 4, "interop %d type" % i),
                })

    # -- step 5: names ------------------------------------------------------

    def _resolve_names(self):
        nulls = sum(1 for t in self.tags if t.offset is None)
        if nulls:
            self.diag.note("%d of %d tag table entries are null. In Reach that normally means the tag "
                           "lives in a shared cache (shared.map / campaign.map) rather than in this map."
                           % (nulls, len(self.tags)))
        for g in self.groups:
            g.name = self.resolve_sid(g.name_sid) or GROUP_NAMES.get(g.code, "")
            if not g.name:
                g.name = GROUP_NAMES.get(g.code, "")
        if self.tag_names and len(self.tag_names) != len(self.tags):
            self.diag.warn("tag name table has %d entries but the tag table has %d; "
                           "names are matched by index so one of them is wrong"
                           % (len(self.tag_names), len(self.tags)))
        for t in self.tags:
            if t.index < len(self.tag_names):
                t.path = self.tag_names[t.index]
            g = self._group_by_code.get(t.group_code)
            t.group_name = (g.name if g else "") or GROUP_NAMES.get(t.group_code, "")

    def estimate_sizes(self):
        """Estimate each tag's data extent.

        The Reach tag table stores NO size: a tag entry is only
        (group index, salt, address).  Assembly reads a tag's fields through a
        plugin layout instead of needing a size.  Here the extent is estimated
        as the gap to the next tag address in the meta area, with the last tag
        running to the end of the area.  HEURISTIC: a dump may include trailing
        padding or, if the author inserted data, more than one tag's worth.
        """
        live = sorted((t for t in self.tags if t.offset is not None), key=lambda t: t.offset)
        end = self.meta_offset + self.meta_size
        for i, t in enumerate(live):
            nxt = live[i + 1].offset if i + 1 < len(live) else end
            size = max(0, min(nxt, end, len(self.data)) - t.offset)
            t.size = size

    # -- queries ------------------------------------------------------------

    def tags_of_group(self, code: str):
        return [t for t in self.tags if t.group_code == code]

    def global_tag(self, code: str):
        idx = self.global_tags.get(code)
        if idx is None or idx >= len(self.tags):
            return None
        return self.tags[idx]

    def tag_bytes(self, tag: TagEntry) -> bytes:
        if tag.offset is None:
            raise MapFormatError("tag %d (%s) is null; nothing to read" % (tag.index, tag.group_code))
        return self.reader.raw(tag.offset, tag.size or 0, "tag %d data" % tag.index)

    def meta_bytes(self) -> bytes:
        return self.reader.raw(self.meta_offset, self.meta_size, "tag data area")

    def build_date(self):
        """FILETIME (high, low) -> ISO string, or None."""
        hi = self.header.get("cache_build_date_high") or 0
        lo = self.header.get("cache_build_date_low") or 0
        ft = ((hi & 0xFFFFFFFF) << 32) | (lo & 0xFFFFFFFF)
        if ft == 0:
            return None
        try:
            import datetime
            # FILETIME: 100 ns ticks since 1601-01-01 UTC
            seconds = ft / 10_000_000 - 11_644_473_600
            if not (0 < seconds < 4_000_000_000):
                return None
            return datetime.datetime.fromtimestamp(seconds, datetime.timezone.utc).isoformat()
        except Exception:
            return None

    def summary(self) -> dict:
        return {
            "path": self.path,
            "file_size_actual": len(self.data),
            "endian": "little" if self.endian == "<" else "big",
            "engine_version": self.engine_version,
            "header_layout": self.variant.name,
            "header_layout_notes": self.variant.notes,
            "engine": self.engine_name,
            "build_string": self.build_string,
            "detection": self.detection,
            "footer_magic_ok": self.footer_ok,
            "header_size": self.variant.header_size,
            "cache_type": CACHE_FILE_TYPES.get(self.header.get("type"), "unknown(%r)" % self.header.get("type")),
            "internal_name": self.header.get("internal_name"),
            "scenario_name": self.header.get("scenario_name"),
            "build_date": self.build_date(),
            "checksum": self.header.get("checksum"),
            "xdk_version": self.header.get("xdk_version"),
            "virtual_base_address": self.header.get("virtual_base_address"),
            "tag_data_offset": self.meta_offset,
            "tag_data_size": self.meta_size,
            "tag_data_source": self.section_source,
            "expand_magic": self.variant.expand_magic,
            "sections": [{"name": SECTION_NAMES[i], "virtual_address": s[0], "size": s[1],
                          "offset_mask": self.offset_masks[i]} for i, s in enumerate(self.sections)],
            "partitions": self.partitions,
            "index_header": self.index_header,
            "counts": {
                "tag_groups": len(self.groups),
                "tags": len(self.tags),
                "null_tags": sum(1 for t in self.tags if t.offset is None),
                "global_tags": len(self.global_tags),
                "tag_interops": len(self.interops),
                "tag_names": len(self.tag_names),
                "string_ids": len(self.stringids),
            },
            "global_tags": {k: v for k, v in sorted(self.global_tags.items())},
            "warnings": self.diag.warnings,
            "notes": self.diag.notes,
        }


