def _safe_name(path: str | None, group: str, index: int) -> str:
    base = (path or "unnamed").replace("\\", "_").replace("/", "_")
    base = "".join(c if (c.isalnum() or c in "._-") else "_" for c in base)[:96]
    grp = "".join(c if c.isalnum() else "_" for c in group) or "none"
    return "%04d_%s_%s" % (index, grp, base)


def extract(cache: ReachCacheFile, outdir: Path, groups=INTERESTING_GROUPS,
            all_tags: bool = False, dump_meta: bool = False) -> dict:
    """Write the listing plus per-tag blobs under ``outdir``. Returns a manifest."""
    outdir = Path(outdir)
    tagdir = outdir / "tags"
    outdir.mkdir(parents=True, exist_ok=True)
    tagdir.mkdir(parents=True, exist_ok=True)

    summary = cache.summary()
    (outdir / "header.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8")

    rows = ["index\tdatum\tgroup\tgroup_name\tfile_offset\test_size\tvirtual_address\tpath"]
    for t in cache.tags:
        rows.append("%d\t0x%08X\t%s\t%s\t%s\t%s\t0x%X\t%s" % (
            t.index, t.datum, t.group_code, t.group_name,
            ("0x%X" % t.offset) if t.offset is not None else "-",
            ("0x%X" % t.size) if t.size is not None else "-",
            t.address, t.path if t.path is not None else ""))
    (outdir / "tags.tsv").write_text("\n".join(rows) + "\n", encoding="utf-8")

    (outdir / "tags.json").write_text(json.dumps([{
        "index": t.index, "datum": t.datum, "group": t.group_code, "group_name": t.group_name,
        "path": t.path, "virtual_address": t.address, "raw_address": t.raw_address,
        "file_offset": t.offset, "estimated_size": t.size,
    } for t in cache.tags], indent=1), encoding="utf-8")

    (outdir / "tag_groups.tsv").write_text(
        "\n".join(["code\tparent\tname\tname_sid"] +
                  ["%s\t%s\t%s\t0x%08X" % (g.code, g.parent_code, g.name, g.name_sid)
                   for g in cache.groups]) + "\n", encoding="utf-8")

    if cache.tag_names:
        (outdir / "tag_names.txt").write_text(
            "\n".join("%d\t%s" % (i, n if n is not None else "<null>")
                      for i, n in enumerate(cache.tag_names)) + "\n", encoding="utf-8")
    if cache.stringids:
        (outdir / "stringids.txt").write_text(
            "\n".join("%d\t%s" % (i, s if s is not None else "<null>")
                      for i, s in enumerate(cache.stringids)) + "\n", encoding="utf-8")

    manifest = {"outdir": str(outdir), "written": [], "skipped": [], "errors": []}
    wanted = set(groups)
    for t in cache.tags:
        if not all_tags and t.group_code not in wanted:
            continue
        if t.offset is None or not t.size:
            manifest["skipped"].append({"index": t.index, "group": t.group_code,
                                        "reason": "null tag" if t.offset is None else "zero size"})
            continue
        stem = _safe_name(t.path, t.group_code, t.index)
        blob_path = tagdir / (stem + ".bin")
        try:
            blob_path.write_bytes(cache.tag_bytes(t))
        except MapFormatError as exc:
            manifest["errors"].append({"index": t.index, "error": str(exc)})
            continue
        sidecar = {
            "index": t.index, "datum": "0x%08X" % t.datum, "group": t.group_code,
            "group_name": t.group_name, "path": t.path,
            "virtual_address": t.address, "raw_address_in_tag_table": t.raw_address,
            "file_offset_in_map": t.offset, "size_bytes": t.size,
            "size_is_estimated": True,
            "map": cache.path, "map_build_string": cache.build_string,
            "header_layout": cache.variant.name,
            "pointer_math": {
                "expand": "virtual = (stored32 << 2) + 0x%X" % cache.variant.expand_magic
                          if cache.variant.expand_magic else "virtual = stored32 (no contraction)",
                "map_file_offset": "offset = virtual - 0x%X + 0x%X" % (cache.virtual_base, cache.meta_offset),
                "offset_within_this_dump": "offset = virtual - 0x%X" % t.address,
            },
        }
        (tagdir / (stem + ".json")).write_text(json.dumps(sidecar, indent=2), encoding="utf-8")
        manifest["written"].append({"index": t.index, "group": t.group_code,
                                    "file": str(blob_path), "size": t.size})

    # hsc* source text, best effort
    hsc_tags = cache.tags_of_group("hsc*")
    if hsc_tags:
        hscdir = outdir / "hsc"
        hscdir.mkdir(exist_ok=True)
        for t in hsc_tags:
            try:
                name, text = read_hsc_source(cache, t)
            except MapFormatError as exc:
                manifest["errors"].append({"index": t.index, "error": "hsc*: %s" % exc})
                continue
            fn = "".join(c if (c.isalnum() or c in "._-") else "_" for c in (name or "script"))
            (hscdir / ("%04d_%s.hsc" % (t.index, fn))).write_text(text, encoding="utf-8")
            manifest["written"].append({"index": t.index, "group": "hsc*",
                                        "file": str(hscdir / ("%04d_%s.hsc" % (t.index, fn))),
                                        "size": len(text)})

    if dump_meta:
        (outdir / "meta.bin").write_bytes(cache.meta_bytes())
        manifest["written"].append({"index": None, "group": "<tag data area>",
                                    "file": str(outdir / "meta.bin"), "size": cache.meta_size})

    (outdir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest
