def read_hsc_source(cache: ReachCacheFile, tag: TagEntry):
    """Decode an ``hsc*`` tag into (name, source_text).  SPEC-CITED, UNTESTED.

    Layout from Assembly ReachMCC_Layouts_Core.xml ``<layout for="hsc*">``:
      0x00 asciiz  file name
      0x20 int32   source size
      0x2C uint32  source pointer (contracted)
    """
    if tag.offset is None:
        raise MapFormatError("hsc* tag %d is null" % tag.index)
    rd = cache.reader
    name = rd.asciiz(tag.offset, 0x20, "hsc* %d name" % tag.index)
    size = rd.scalar("i32", tag.offset + 0x20, "hsc* %d source size" % tag.index)
    ptr = rd.scalar("u32", tag.offset + 0x2C, "hsc* %d source pointer" % tag.index)
    if size <= 0 or size > 0x400000:
        raise MapFormatError("hsc* tag %d claims source size 0x%X, which is not plausible" % (tag.index, size))
    off = cache.meta_to_offset(cache.expand(ptr), "hsc* %d source" % tag.index)
    blob = rd.raw(off, size, "hsc* %d source" % tag.index)
    return name, blob.split(b"\x00", 1)[0].decode("latin-1")


