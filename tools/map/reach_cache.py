def probe_compression(data: bytes) -> list:
    """Guess what a non-cache-looking file actually is.

    Returns a list of human-readable findings. Knowledge comes from
    Assembly's src/Blamite/Compression/*.cs and Formats/Engines.xml:

      * ``none``    -- every PC MCC engine (Halo 3 / ODST / Reach / Halo 4 MCC
                       on PC) declares NO compression; shipped PC .map files are
                       flat cache files with "daeh" at offset 0.
      * ``ceamcc``  -- Halo 1 Anniversary MCC: int32 chunk count at 0x0, then
                       that many int32 chunk offsets; each chunk is
                       [int32 decompressed size][2-byte zlib header][deflate].
      * ``h2mcc``   -- Halo 2 MCC: uncompressed header, then a chunk table of
                       (int32 compressed size, int32 offset) pairs; negative
                       size = stored raw; chunk size 0x40000.
      * ``xb1mcc``  -- Xbox One 2014 MCC builds of H2A/H3/H4: the four interop
                       *sections* are individually compressed, type 0 = raw,
                       type 3 = LZMA with a packed dictionary-size byte.
                       Reach has no such build, so this cannot apply to a Reach map.
      * ``cea360``  -- Halo 1 Anniversary 360: LZX, unsupported even by Assembly.
    """
    out = []
    if len(data) < 16:
        out.append("file is only %d bytes long" % len(data))
        return out
    head = data[:4]
    if head in MODULE_MAGICS:
        out.append("magic %r: this is a Halo Infinite-style .module, not a blam cache file" % head)
        return out
    if head[:1] == b"\x78":
        out.append("starts with a raw zlib stream (0x78 ...); try `python3 -c \"import zlib,sys;"
                   "sys.stdout.buffer.write(zlib.decompress(open(sys.argv[1],'rb').read()))\" map`")
    if data[0] == 0x5D:
        out.append("starts with 0x5D: looks like a bare LZMA1 (alone) stream")
    if data[:6] == b"\xFD7zXZ\x00":
        out.append("starts with the XZ magic")
    if data[:2] == b"PK":
        out.append("starts with 'PK': this is a zip archive, not a cache file")
    # CEA-MCC style chunk table at 0x0 (Assembly FirstGenSaberZLib)
    count = struct.unpack_from("<I", data, 0)[0]
    if 0 < count < 0x10000 and 4 + count * 4 <= len(data):
        first = struct.unpack_from("<I", data, 4)[0]
        if 0 < first < len(data) - 8:
            tail = data[first + 4:first + 6]
            if tail[:1] == b"\x78":
                out.append("chunk count 0x%X at 0x0 and a zlib header at chunk 0 (0x%X): matches the "
                           "Saber/CEA-MCC chunked-zlib scheme (Assembly: ceamcc)" % (count, first))
    # H2-MCC style chunk table right after a 0x800 header
    if len(data) > 0x810:
        csize, coff = struct.unpack_from("<iI", data, 0x800)
        if csize != 0 and 0 < coff < len(data):
            out.append("a (size=0x%X, offset=0x%X) pair sits at 0x800: could be the H2-MCC chunk table "
                       "(Assembly: h2mcc, chunk size 0x40000)" % (csize & 0xFFFFFFFF, coff))
    if not out:
        out.append("no known cache magic and no recognised compression signature; "
                   "first 16 bytes = %s" % data[:16].hex(" "))
    return out


def decompress_saber_gen1(data: bytes) -> bytes:
    """Halo 1 Anniversary MCC ("ceamcc") chunked zlib.  UNTESTED.

    Transcribed from Assembly src/Blamite/Compression/FirstGenSaberZLib.cs.
    Included only so that a surprise compressed file can be unpacked; a Reach
    map should never need this.
    """
    count = struct.unpack_from("<i", data, 0)[0]
    if count <= 0 or 4 + count * 4 > len(data):
        raise MapFormatError("saber-gen1: implausible chunk count %d" % count)
    offsets = list(struct.unpack_from("<%di" % count, data, 4))
    out = bytearray()
    for i, off in enumerate(offsets):
        if not (0 <= off < len(data)):
            raise MapFormatError("saber-gen1: chunk %d offset 0x%X past EOF 0x%X" % (i, off, len(data)))
        real = struct.unpack_from("<i", data, off)[0]
        blob = data[off + 6:]            # +4 size, +2 zlib header
        chunk = zlib.decompressobj(-15).decompress(blob, real)
        if len(chunk) != real:
            raise MapFormatError("saber-gen1: chunk %d decompressed to 0x%X, expected 0x%X"
                                 % (i, len(chunk), real))
        out += chunk
    return bytes(out)


def decompress_saber_gen2(data: bytes, header_size: int = 0x800,
                          chunk_size: int = 0x40000, max_chunks: int = 0x400) -> bytes:
    """Halo 2 MCC ("h2mcc") chunked zlib.  UNTESTED.

    Transcribed from Assembly src/Blamite/Compression/SecondGenSaberZLib.cs.
    """
    out = bytearray(data[:header_size])
    pos = header_size
    chunks = []
    for i in range(max_chunks):
        if pos + 8 > len(data):
            break
        csize, coff = struct.unpack_from("<iI", data, pos)
        pos += 8
        if csize == 0:
            break
        if coff >= len(data):
            raise MapFormatError("saber-gen2: chunk %d offset 0x%X past EOF" % (i, coff))
        chunks.append((csize, coff))
    for i, (csize, coff) in enumerate(chunks):
        if csize < 0:                     # stored raw ("faux compression")
            out += data[coff:coff - csize]
        else:
            chunk = zlib.decompressobj(-15).decompress(data[coff + 2:], chunk_size)
            out += chunk
    return bytes(out)


